#ifndef UTILS_H
#define UTILS_H

void str_trim(char *s);
int  is_all_digit(const char *s);

/* --------------------------------------------------------------------------
 * 终端表格对齐用的三个函数
 * --------------------------------------------------------------------------
 * printf 的 "%-10s" 是按【字节】补空格的，而一个汉字在 UTF-8 里占 3 字节、
 * 在屏幕上只占 2 列，所以中英混排的表格直接用 %-10s 必然歪。
 * 表格一律改用 table_row() 打印。
 * -------------------------------------------------------------------------- */

/* UTF-8 字符串的显示宽度：汉字/全角/假名/谚文算 2 列，其余算 1 列。
 * 非法字节按 1 列算（不崩、不卡死）。*/
int  utf8_width(const char *s);

/* 是否是合法 UTF-8（含"过长编码"、代理对、超出 U+10FFFF 的检查）。
 * 返回 1 合法，0 不合法。
 * 用途：终端或粘贴内容的编码不是 UTF-8 时（例如 GBK），程序收到的字节
 * 原样发给 MySQL 会被拒（报 Incorrect string value），在输入处先拦下来
 * 才能给出看得懂的提示。*/
int  utf8_valid(const char *s);

/* 打印一行表格。
 * 参数：cells   各列的字符串，如 {"P20260001", "张三", "男"}
 *       widths  各列的显示宽度；取负数表示这一列右对齐（数字、金额用）
 *       n       列数
 * 说明：按显示宽度补空格，列与列之间留一个空格，最后一列打印完直接换行。
 *       一行内要打印的数字（年龄、单价……）先 snprintf 进小缓冲区再传进来。*/
void table_row(const char *cells[], const int widths[], int n);

#endif
