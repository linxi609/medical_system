/* ==========================================================================
 * doctor.h —— M02 医生信息管理
 * --------------------------------------------------------------------------
 * 负责组：管理员组
 * 对应表：t_doctor
 * 功能：管理员新增医生账号、处理离职、修改职称/科室/电话；
 *       患者挂号时可查询医生列表。
 *
 * 【返回值约定】本模块函数使用以下返回值，各函数只会用到其中一部分：
 *    0   成功
 *   -1   数据库连接失败
 *   -2   SQL 执行失败
 *   -3   登录账号已存在（唯一约束冲突）
 *   -4   医生不存在或已离职
 * ========================================================================== */

#ifndef DOCTOR_H
#define DOCTOR_H

#include "db_mysql.h"

/* 医生信息，对应表 t_doctor 的一行 */
typedef struct {
    char doctor_id[10];     /* 医生编号，形如 D001，新增时自动生成 */
    char name[50];          /* 姓名 */
    char gender[12];        /* 性别，如 "男" / "女"（长度取法见 patient.h 的说明） */
    char title[20];         /* 职称，如 "主治医师" */
    char dept[50];          /* 所属科室，如 "内科"。科室只是本字段的字符串，不单独建表 */
    char phone[20];         /* 联系电话 */
    char username[50];      /* 登录账号，新增时由系统设成医生编号（如 D001），全局唯一 */
    char password[100];     /* 登录密码 */
    int  status;            /* 状态：1 在职，0 离职（离职后不能登录） */
} Doctor;

/* --------------------------------------------------------------------------
 * 新增医生
 * 参数：db  已连接的数据库句柄
 *       d   [入参+出参] 医生信息。除 doctor_id、username 外各字段由调用者填好；
 *           函数内部按 "D + 3 位流水号" 生成编号，并把登录账号 username
 *           设成同一个编号（管理员不用另起账号名），
 *           成功后回写到 d->doctor_id 和 d->username
 * 返回：0 成功；-3 登录账号已存在；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int doctor_add(DB_HANDLE* db, Doctor* d);

/* --------------------------------------------------------------------------
 * 医生离职（软删除）
 * 参数：db         已连接的数据库句柄
 *       doctor_id  医生编号
 * 说明：把 status 置 0，不删数据。离职医生不能再登录
 * 返回：0 成功；-4 医生不存在；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int doctor_delete(DB_HANDLE* db, const char* doctor_id);

/* --------------------------------------------------------------------------
 * 修改医生信息
 * 参数：db  已连接的数据库句柄
 *       d   医生信息，按 d->doctor_id 定位，其余字段为改后的值
 * 说明：管理员改职称/科室/电话；医生本人在"修改资料"中调用时只传可改字段
 * 返回：0 成功；-4 医生不存在；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int doctor_update(DB_HANDLE* db, const Doctor* d);

/* --------------------------------------------------------------------------
 * 按编号查询医生
 * 参数：db         已连接的数据库句柄
 *       doctor_id  医生编号
 *       out        [出参] 查询结果写入此处
 * 返回：0 成功；-4 未找到；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int doctor_query_by_id(DB_HANDLE* db, const char* doctor_id, Doctor* out);

/* --------------------------------------------------------------------------
 * 查询医生列表
 * 参数：db         已连接的数据库句柄
 *       out_list   [出参] 函数内部 malloc 出数组，用完必须调 doctor_list_free
 *       out_count  [出参] 结果条数
 * 说明：患者挂号时用它列出可选医生（只列在职的）
 * 返回：0 成功（可能 out_count 为 0）；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int doctor_query_all(DB_HANDLE* db, Doctor** out_list, int* out_count);

/* --------------------------------------------------------------------------
 * 释放 doctor_query_all 返回的数组
 * 参数：list  doctor_query_all 得到的数组，传 NULL 也安全
 * -------------------------------------------------------------------------- */
void doctor_list_free(Doctor* list);

#endif /* DOCTOR_H */
