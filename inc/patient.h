/* ==========================================================================
 * patient.h —— M01 患者档案管理
 * --------------------------------------------------------------------------
 * 负责组：患者组
 * 对应表：t_patient
 * 功能：患者自助注册建档；管理员查看、修改、注销、导出患者信息；
 *       患者可修改本人联系方式。
 *
 * 【返回值约定】本模块函数使用以下返回值，各函数只会用到其中一部分：
 *    0   成功
 *   -1   数据库连接失败
 *   -2   SQL 执行失败
 *   -3   身份证号或登录账号已存在（唯一约束冲突）
 *   -4   患者不存在或已注销
 * ========================================================================== */

#ifndef PATIENT_H
#define PATIENT_H

#include "db_mysql.h"

/* 患者信息，对应表 t_patient 的一行
 *
 * 【字段长度怎么取】两个坑，取宽度时必须都算上：
 *
 *   1) 末尾要留一个字节放 '\0'。18 位的身份证号需要 char[19]，不是 char[18]。
 *
 *   2) MySQL 的 VARCHAR(n) 按【字符】算，C 的 char 数组按【字节】算，
 *      两者不是一个单位。一个汉字在 UTF-8 里占 3 个字节，
 *      所以放中文的字段要按“字符数 × 3 + 1”估算。
 *
 * 取窄了的后果不只是截断：装不下的部分会留在输入缓冲区里，
 * 被下一个问题读走，把后面每个字段都顶错一位，而且全程不报错。
 * 性别字段就踩过这个坑（char[4] 连 "男\n" 都装不下，换行符漏到了下一项）。 */
typedef struct {
    char patient_id[20];    /* 患者编号，形如 P20260001，注册时自动生成，不可修改 */
    char name[50];          /* 姓名 */
    char gender[12];        /* 性别，如 "男" / "女" */
    int  age;               /* 年龄 */
    char id_card[19];       /* 身份证号，全局唯一。18 位，如 110101199001011234 */
    char phone[20];         /* 联系电话，患者本人可自行修改 */
    char address[200];      /* 家庭住址，患者本人可自行修改 */
    char username[50];      /* 登录账号，注册时由系统设成患者编号（如 P20260001），全局唯一 */
    char password[100];     /* 登录密码 */
    char create_time[20];   /* 注册时间，格式 "YYYY-MM-DD HH:MM:SS" */
    int  status;            /* 状态：1 正常，0 已注销（软删除） */
} Patient;

/* --------------------------------------------------------------------------
 * 患者注册建档
 * 参数：db  已连接的数据库句柄
 *       p   [入参+出参] 患者信息。除 patient_id、username 外各字段需由调用者填好；
 *           函数内部按 "P + 年份 + 4 位流水号" 生成编号，并把登录账号
 *           username 设成同一个编号（患者不用自己起账号），
 *           成功后回写到 p->patient_id 和 p->username
 * 返回：0 成功；-3 身份证号或账号已存在；-2 SQL 执行失败；-1 连接失败
 * -------------------------------------------------------------------------- */
int patient_register(DB_HANDLE* db, Patient* p);

/* --------------------------------------------------------------------------
 * 患者修改本人联系方式
 * 参数：db          已连接的数据库句柄
 *       patient_id  患者编号
 *       phone       新电话
 *       address     新住址
 * 说明：只能改电话和住址。身份证号和患者编号不允许患者自行修改
 * 返回：0 成功；-4 患者不存在；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int patient_update_self(DB_HANDLE* db, const char* patient_id,
                        const char* phone, const char* address);

/* --------------------------------------------------------------------------
 * 按编号查询患者
 * 参数：db          已连接的数据库句柄
 *       patient_id  患者编号
 *       out         [出参] 查询结果写入此处
 * 返回：0 成功；-4 未找到；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int patient_query_by_id(DB_HANDLE* db, const char* patient_id, Patient* out);

/* --------------------------------------------------------------------------
 * 查询全部患者（管理员用）
 * 参数：db         已连接的数据库句柄
 *       out_list   [出参] 函数内部 malloc 出数组，用完必须调 patient_list_free
 *       out_count  [出参] 结果条数
 * 返回：0 成功（可能 out_count 为 0）；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int patient_query_all(DB_HANDLE* db, Patient** out_list, int* out_count);

/* --------------------------------------------------------------------------
 * 释放 patient_query_all 返回的数组
 * 参数：list  patient_query_all 得到的数组，传 NULL 也安全
 * -------------------------------------------------------------------------- */
void patient_list_free(Patient* list);

/* --------------------------------------------------------------------------
 * 注销患者（软删除）
 * 参数：db          已连接的数据库句柄
 *       patient_id  患者编号
 * 说明：把 status 置 0，不删数据。注销后该患者不能登录、不能挂号
 * 返回：0 成功；-4 患者不存在；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int patient_delete(DB_HANDLE* db, const char* patient_id);

/* --------------------------------------------------------------------------
 * 导出患者列表到文本文件
 * 参数：db       已连接的数据库句柄
 *       filename 目标文件名，如 "data/patients_export_20260927.txt"。
 *                目录必须已存在，本函数不建目录（菜单层会先把目录准备好）
 * 返回：0 成功；-2 查询失败；-3 写文件失败（目录不存在、没权限等）
 * -------------------------------------------------------------------------- */
int patient_export(DB_HANDLE* db, const char* filename);

#endif /* PATIENT_H */
