/* ==========================================================================
 * medicine.h —— M06 药品库存管理
 * --------------------------------------------------------------------------
 * 负责组：管理员组（入库/出库/调价/盘点）、医生组（开方前查库存）
 * 对应表：t_medicine
 * 功能：药品入库、出库、调价、盘点和库存查询。
 *
 * 【库存预警】库存低于 50 视为不足。列表展示时，stock < 50 的行要标注
 * "库存不足"。判断时直接写 50（本项目不使用常量宏）。
 *
 * 【返回值约定】本模块函数使用以下返回值，各函数只会用到其中一部分：
 *    0   成功
 *   -1   数据库连接失败
 *   -2   SQL 执行失败
 *   -3   药品编号已存在（唯一约束冲突）
 *   -4   药品不存在
 *   -5   出库数量大于当前库存，拒绝出库
 *   -6   药品已被历史处方引用，不允许删除
 * ========================================================================== */

#ifndef MEDICINE_H
#define MEDICINE_H

#include "db_mysql.h"

/* 药品信息，对应表 t_medicine 的一行 */
typedef struct {
    char   med_id[20];      /* 药品编号，如 M001 */
    char   med_name[50];    /* 药品名称 */
    char   spec[50];        /* 规格，如 "0.25g*24粒" */
    char   unit[10];        /* 单位，如 "盒" */
    double price;           /* 单价 */
    int    stock;           /* 当前库存 */
    char   manufacturer[50];/* 生产厂家 */
} Medicine;

/* --------------------------------------------------------------------------
 * 新增药品
 * 参数：db  已连接的数据库句柄
 *       m   药品信息，各字段由调用者填好
 * 返回：0 成功；-3 药品编号已存在；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int medicine_add(DB_HANDLE* db, const Medicine* m);

/* --------------------------------------------------------------------------
 * 入库：增加库存
 * 参数：db        已连接的数据库句柄
 *       med_id    药品编号
 *       quantity  入库数量，必须大于 0
 * 返回：0 成功；-4 药品不存在；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int medicine_stock_in(DB_HANDLE* db, const char* med_id, int quantity);

/* --------------------------------------------------------------------------
 * 出库：减少库存
 * 参数：db        已连接的数据库句柄
 *       med_id    药品编号
 *       quantity  出库数量，必须大于 0
 * 说明：出库数量不能大于当前库存。开处方时的扣库存不走这个函数，
 *       而是由 prescription_add 在自己的事务里直接扣
 * 返回：0 成功；-4 药品不存在；-5 库存不足；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int medicine_stock_out(DB_HANDLE* db, const char* med_id, int quantity);

/* --------------------------------------------------------------------------
 * 调价：直接更新单价
 * 参数：db         已连接的数据库句柄
 *       med_id     药品编号
 *       new_price  新单价，必须大于等于 0
 * 说明：只改 t_medicine.price。已开出处方里的 unit_price 是快照，不受影响
 * 返回：0 成功；-4 药品不存在；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int medicine_update_price(DB_HANDLE* db, const char* med_id, double new_price);

/* --------------------------------------------------------------------------
 * 删除药品
 * 参数：db      已连接的数据库句柄
 *       med_id  药品编号
 * 说明：真删（DELETE），不是软删除。删除前会查 t_presc_detail：
 *       只要该药品在历史处方明细里出现过就拒绝删除，避免历史处方对不上号
 * 返回：0 成功；-4 药品不存在；-6 已被历史处方引用；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int medicine_delete(DB_HANDLE* db, const char* med_id);

/* --------------------------------------------------------------------------
 * 查询全部药品（盘点用）
 * 参数：db         已连接的数据库句柄
 *       out_list   [出参] 函数内部 malloc 出数组，用完必须调 medicine_list_free
 *       out_count  [出参] 结果条数
 * 返回：0 成功（可能 out_count 为 0）；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int medicine_query_all(DB_HANDLE* db, Medicine** out_list, int* out_count);

/* --------------------------------------------------------------------------
 * 按编号查询单个药品（医生开方前查库存用）
 * 参数：db      已连接的数据库句柄
 *       med_id  药品编号
 *       out     [出参] 查询结果写入此处
 * 返回：0 成功；-4 未找到；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int medicine_query_by_id(DB_HANDLE* db, const char* med_id, Medicine* out);

/* --------------------------------------------------------------------------
 * 释放 medicine_query_all 返回的数组
 * 参数：list  medicine_query_all 得到的数组，传 NULL 也安全
 * -------------------------------------------------------------------------- */
void medicine_list_free(Medicine* list);

#endif /* MEDICINE_H */
