/* ==========================================================================
 * auth.h —— M08 登录与用户
 * --------------------------------------------------------------------------
 * 负责组：三组共用（登录入口在主菜单，各角色都要用）
 * 对应表：t_admin、t_doctor、t_patient
 * 功能：三类角色使用统一登录入口；患者注册时开通登录账号；
 *       所有用户可修改本人密码。
 *
 * 【角色取值】数据库里没有统一的角色字段——三类用户分别存在三张表。
 *   登录时靠"查的是哪张表"来确定角色，代码里用以下数字表示：
 *    1 = 管理员 admin
 *    2 = 医生   doctor
 *    3 = 患者   patient
 *
 * 【登录规则】
 *   - admin 账号由 init.sql 预置（admin / 123456）
 *   - doctor 由管理员创建，登录账号就是医生编号（如 D001），密码由管理员设定
 *   - patient 自助注册，登录账号就是患者编号（如 P20260001），密码本人设定
 *   - 账号一律由系统生成、不复用：注销/离职后编号和账号都保留，
 *     新患者、新医生拿新编号，不会出现"重名注册不进来"的问题
 *   - 连续 5 次登录失败，账号锁定 10 分钟
 *   - 密码目前明文存储，部署时把 hash_password 换成加盐哈希
 *
 * 【锁定状态存在哪】三张用户表都【没有】失败次数和锁定时间的字段，
 *   也不要去加——那会改动表结构，和"改表一律走 init.sql"的约定冲突。
 *   正确做法：在 auth.c 里用 static 变量自己存一张表，记录
 *   "用户名 → 连续失败次数、锁到什么时候"。
 *   单进程运行完全够用。缺点是程序重启后计数清零，本项目可以接受。
 *
 * 【返回值约定】本模块函数使用以下返回值，各函数只会用到其中一部分：
 *    0   成功
 *   -1   数据库连接失败
 *   -2   SQL 执行失败
 *   -3   注册时身份证号已存在
 *   -4   账号或密码错误
 *   -6   角色与账号不匹配
 *   -7   账号已锁定（连续失败 5 次，锁 10 分钟）或账号已注销/离职
 * ========================================================================== */

#ifndef AUTH_H
#define AUTH_H

#include "db_mysql.h"
#include "patient.h"

/* 登录成功后的用户信息，主菜单据此显示欢迎语、分发功能、做权限判断 */
typedef struct {
    char id[20];        /* 用户编号：管理员 A001 / 医生 D001 / 患者 P20260001 */
    char name[50];      /* 姓名，用于欢迎语 */
    int  role;          /* 角色：1 管理员，2 医生，3 患者 */
} LoginUser;

/* --------------------------------------------------------------------------
 * 登录
 * 参数：db        已连接的数据库句柄
 *       role      选择的身份：1 管理员，2 医生，3 患者
 *       username  登录账号（医生是 D 开头的医生编号，患者是 P 开头的患者编号）
 *       password  密码
 *       out       [出参] 登录成功时写入用户信息，供主菜单使用
 * 说明：按 role 决定查哪张表。查到的用户 status 必须是 1（未注销/未离职），
 *       否则当作登录失败处理
 * 返回：0 成功；-4 账号或密码错误；-6 该账号不属于所选身份；
 *       -7 账号已锁定或已注销/离职；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int user_login(DB_HANDLE* db, int role, const char* username,
               const char* password, LoginUser* out);

/* --------------------------------------------------------------------------
 * 患者注册（菜单入口）
 * 参数：db  已连接的数据库句柄
 *       p   [入参+出参] 患者信息，其中 patient_id、username 由函数生成后回写
 *       （username 和 patient_id 是同一个值，所以入参里不用填 username）
 * 说明：注册流程的入口——采集输入 → 校验身份证号唯一 →
 *       建档入库。建档动作调用 patient_register 完成，
 *       本函数只负责注册流程的校验和提示
 * 返回：0 成功；-3 身份证号已存在；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int user_register_patient(DB_HANDLE* db, Patient* p);

/* --------------------------------------------------------------------------
 * 修改本人密码
 * 参数：db         已连接的数据库句柄
 *       role       角色：1 管理员，2 医生，3 患者
 *       id         本人编号
 *       old_pwd    原密码，必须校验正确才允许修改
 *       new_pwd    新密码
 * 返回：0 成功；-4 原密码错误；-2 SQL 执行失败
 * -------------------------------------------------------------------------- */
int user_change_password(DB_HANDLE* db, int role, const char* id,
                         const char* old_pwd, const char* new_pwd);

/* --------------------------------------------------------------------------
 * 密码处理（预留接口）
 * 参数：plain  明文密码
 * 返回：处理后的密码字符串
 * 说明：当前教学阶段直接返回明文副本，保证功能可用。
 *       实际部署时改为加盐 SHA-256，调用处不需要改动。
 *       返回的字符串由函数内部 malloc，调用者负责 free
 * -------------------------------------------------------------------------- */
char* hash_password(const char* plain);

#endif /* AUTH_H */
